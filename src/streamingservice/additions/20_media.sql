CREATE TABLE contentmedia (
  content_id integer NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'queued',
  source_file varchar(255) NOT NULL,
  requested_at timestamp NOT NULL,
  claimed_until timestamp DEFAULT NULL,
  attempts integer NOT NULL DEFAULT 0,
  packaged_at timestamp DEFAULT NULL,
  storage_path text,
  hls_path text,
  dash_path text,
  duration_seconds real DEFAULT NULL,
  error text,
  PRIMARY KEY (content_id),
  CONSTRAINT contentmedia_ibfk_1 FOREIGN KEY (content_id) REFERENCES content (content_id)
);

CREATE INDEX idx_contentmedia_status ON contentmedia (status, requested_at);

CREATE TABLE rendition (
  rendition_id integer GENERATED BY DEFAULT AS IDENTITY,
  content_id integer NOT NULL,
  kind varchar(20) NOT NULL,
  codec varchar(100) NOT NULL,
  bitrate integer NOT NULL,
  width integer DEFAULT NULL,
  height integer DEFAULT NULL,
  language varchar(50) DEFAULT NULL,
  path text NOT NULL,
  PRIMARY KEY (rendition_id),
  CONSTRAINT rendition_ibfk_1 FOREIGN KEY (content_id) REFERENCES contentmedia (content_id) ON DELETE CASCADE
);

CREATE INDEX idx_rendition_content_id ON rendition (content_id);

CREATE TABLE subtitlefile (
  subtitle_id integer NOT NULL,
  uri text NOT NULL,
  format varchar(20) NOT NULL,
  PRIMARY KEY (subtitle_id),
  CONSTRAINT subtitlefile_ibfk_1 FOREIGN KEY (subtitle_id) REFERENCES subtitle (subtitle_id) ON DELETE CASCADE
);

CREATE TABLE playbacksession (
  session_id uuid NOT NULL,
  user_id integer NOT NULL,
  content_id integer NOT NULL,
  device_id varchar(64) NOT NULL,
  started_at timestamp NOT NULL,
  expires_at timestamp NOT NULL,
  ended_at timestamp DEFAULT NULL,
  completion_id uuid DEFAULT NULL,
  completed_at timestamp DEFAULT NULL,
  watched_content_id integer DEFAULT NULL,
  PRIMARY KEY (session_id),
  CONSTRAINT playbacksession_completion_id UNIQUE (completion_id),
  CONSTRAINT playbacksession_ibfk_1 FOREIGN KEY (user_id) REFERENCES "user" (user_id) ON DELETE CASCADE,
  CONSTRAINT playbacksession_ibfk_2 FOREIGN KEY (content_id) REFERENCES content (content_id) ON DELETE CASCADE,
  CONSTRAINT playbacksession_ibfk_3 FOREIGN KEY (watched_content_id) REFERENCES watchhistory ("watched-content_id") ON DELETE SET NULL
);

CREATE INDEX idx_playbacksession_user_id ON playbacksession (user_id, expires_at);

CREATE INDEX idx_playbacksession_content_id ON playbacksession (content_id);

CREATE INDEX idx_playbacksession_watched_content_id ON playbacksession (watched_content_id);

CREATE TABLE playbackposition (
  user_id integer NOT NULL,
  content_id integer NOT NULL,
  "position" real NOT NULL,
  session_id uuid DEFAULT NULL,
  seq bigint NOT NULL DEFAULT 0,
  updated_at timestamp NOT NULL,
  PRIMARY KEY (user_id, content_id),
  CONSTRAINT playbackposition_ibfk_1 FOREIGN KEY (user_id) REFERENCES "user" (user_id) ON DELETE CASCADE,
  CONSTRAINT playbackposition_ibfk_2 FOREIGN KEY (content_id) REFERENCES content (content_id) ON DELETE CASCADE
);

CREATE INDEX idx_playbackposition_content_id ON playbackposition (content_id);
