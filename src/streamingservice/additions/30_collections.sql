CREATE TABLE collection (
  collection_id integer GENERATED BY DEFAULT AS IDENTITY,
  identity_id varchar(450) NOT NULL,
  name varchar(100) NOT NULL,
  created_at timestamp NOT NULL,
  PRIMARY KEY (collection_id),
  CONSTRAINT collection_identity_name UNIQUE (identity_id, name)
);

CREATE TABLE collectiontitle (
  collection_id integer NOT NULL,
  content_id integer NOT NULL,
  position integer NOT NULL,
  added_at timestamp NOT NULL,
  PRIMARY KEY (collection_id, content_id),
  CONSTRAINT collectiontitle_ibfk_1 FOREIGN KEY (collection_id) REFERENCES collection (collection_id) ON DELETE CASCADE,
  CONSTRAINT collectiontitle_ibfk_2 FOREIGN KEY (content_id) REFERENCES content (content_id) ON DELETE CASCADE
);

CREATE INDEX idx_collectiontitle_content_id ON collectiontitle (content_id);
