CREATE TABLE artist (
  artist_id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(100) NOT NULL,
  country varchar(50) DEFAULT NULL,
  formed_date date DEFAULT NULL,
  biography text,
  picture_uri text,
  PRIMARY KEY (artist_id)
);

CREATE INDEX idx_artist_name ON artist (name);

CREATE TABLE album (
  album_id integer GENERATED BY DEFAULT AS IDENTITY,
  title varchar(100) NOT NULL,
  description text,
  release_date date DEFAULT NULL,
  cover_uri text,
  PRIMARY KEY (album_id)
);

CREATE INDEX idx_album_title ON album (title);

CREATE TABLE single (
  single_id integer GENERATED BY DEFAULT AS IDENTITY,
  title varchar(100) NOT NULL,
  release_date date DEFAULT NULL,
  cover_uri text,
  PRIMARY KEY (single_id)
);

CREATE TABLE song (
  song_id integer GENERATED BY DEFAULT AS IDENTITY,
  content_id integer NOT NULL,
  audio_uri text,
  lyrics text,
  PRIMARY KEY (song_id),
  CONSTRAINT song_ibfk_1 FOREIGN KEY (content_id) REFERENCES content (content_id)
);

CREATE INDEX idx_song_content_id ON song (content_id);

CREATE TABLE songartist (
  song_id integer NOT NULL,
  artist_id integer NOT NULL,
  role varchar(50) DEFAULT NULL,
  PRIMARY KEY (song_id, artist_id),
  CONSTRAINT songartist_ibfk_1 FOREIGN KEY (song_id) REFERENCES song (song_id) ON DELETE CASCADE,
  CONSTRAINT songartist_ibfk_2 FOREIGN KEY (artist_id) REFERENCES artist (artist_id) ON DELETE CASCADE
);

CREATE INDEX idx_songartist_artist_id ON songartist (artist_id);

CREATE TABLE albumartist (
  album_id integer NOT NULL,
  artist_id integer NOT NULL,
  PRIMARY KEY (album_id, artist_id),
  CONSTRAINT albumartist_ibfk_1 FOREIGN KEY (album_id) REFERENCES album (album_id) ON DELETE CASCADE,
  CONSTRAINT albumartist_ibfk_2 FOREIGN KEY (artist_id) REFERENCES artist (artist_id) ON DELETE CASCADE
);

CREATE INDEX idx_albumartist_artist_id ON albumartist (artist_id);

CREATE TABLE albumsong (
  album_id integer NOT NULL,
  song_id integer NOT NULL,
  disc_number integer NOT NULL DEFAULT 1,
  track_number integer DEFAULT NULL,
  PRIMARY KEY (album_id, song_id),
  CONSTRAINT albumsong_ibfk_1 FOREIGN KEY (album_id) REFERENCES album (album_id) ON DELETE CASCADE,
  CONSTRAINT albumsong_ibfk_2 FOREIGN KEY (song_id) REFERENCES song (song_id) ON DELETE CASCADE
);

CREATE INDEX idx_albumsong_song_id ON albumsong (song_id);

CREATE TABLE singleartist (
  single_id integer NOT NULL,
  artist_id integer NOT NULL,
  PRIMARY KEY (single_id, artist_id),
  CONSTRAINT singleartist_ibfk_1 FOREIGN KEY (single_id) REFERENCES single (single_id) ON DELETE CASCADE,
  CONSTRAINT singleartist_ibfk_2 FOREIGN KEY (artist_id) REFERENCES artist (artist_id) ON DELETE CASCADE
);

CREATE INDEX idx_singleartist_artist_id ON singleartist (artist_id);

CREATE TABLE singlesong (
  single_id integer NOT NULL,
  song_id integer NOT NULL,
  track_number integer DEFAULT NULL,
  PRIMARY KEY (single_id, song_id),
  CONSTRAINT singlesong_ibfk_1 FOREIGN KEY (single_id) REFERENCES single (single_id) ON DELETE CASCADE,
  CONSTRAINT singlesong_ibfk_2 FOREIGN KEY (song_id) REFERENCES song (song_id) ON DELETE CASCADE
);

CREATE INDEX idx_singlesong_song_id ON singlesong (song_id);
